#!/usr/bin/env python3
"""Builds the 3DS-side data from Axeolon's own output.

Inputs (made by the Java tools in tools/java, run against your Axeolon build):
  generated/blocks.json        DumpBlocks: every block's textures/render type/light
  <textures dir>               ExportTextures: every PNG after Axeolon's texture pipeline
  <assets dir> + index         the vanilla sound/music objects (jars/assets)
  <axeolon dir>                minecraft/src/axeolon (Axeolon's own sounds etc.)

Outputs:
  source/world/BlockTable.cpp  block table compiled into the game
  romfs/textures/*.rgba        raw RGBA images ("AXTX" header) - no PNG decoder needed on 3DS
  romfs/sound/...              .ogg files, same paths the Java SoundManager uses
"""
import json, os, shutil, struct, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def write_rgba(img, path):
    img = img.convert('RGBA')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(b'AXTX' + struct.pack('<HH', img.width, img.height))
        f.write(img.tobytes())

def biome_colour(png, temp, rain):
    # ColorizerGrass/Foliage: rain *= temp; x = (1-temp)*255, y = (1-rain)*255
    im = Image.open(png).convert('RGB')
    rain *= temp
    return im.getpixel((int((1 - temp) * 255), int((1 - rain) * 255)))

# AxeolonColorLight.DYE (BlockDyed.colour): wool colours by metadata
DYE = [0xF0F0F0, 0xF07613, 0xBD44B3, 0x3AAFD9, 0xF8C627, 0x70B919, 0xED8DAC, 0x8E8E86,
       0xC8C8C2, 0x158991, 0x8932B8, 0x2E44D0, 0x83542F, 0x5E7C16, 0xD02020, 0x303040]
# empty tiles in Axeolon's terrain2 half of the atlas, one per tinted glass colour
TINTED_GLASS_TILES = [300, 301, 302, 303, 316, 318, 319, 332, 333, 334, 335, 348, 349, 350, 351, 364]

def tint(img, tile, rgb):
    tx, ty = (tile % 16) * 16, (tile // 16) * 16
    for y in range(ty, ty + 16):
        for x in range(tx, tx + 16):
            r, g, b, a = img.getpixel((x, y))
            img.putpixel((x, y), (r * rgb[0] // 255, g * rgb[1] // 255, b * rgb[2] // 255, a))

def pack_rig_textures(atlas, block_dir):
    # shelf packer, tallest first; writes source/model/RigAtlas.cpp
    ims = []
    for fn in sorted(os.listdir(block_dir)):
        if fn.endswith('.png'):
            ims.append((fn[:-4], Image.open(os.path.join(block_dir, fn)).convert('RGBA')))
    order = sorted(ims, key=lambda t: (-t[1].height, -t[1].width, t[0]))
    x = 0; y = 512; shelf = 0; place = {}
    for name, im in order:
        if x + im.width > 256:
            x = 0; y += shelf; shelf = 0
        if y + im.height > 1024:
            raise SystemExit('rig textures do not fit in the atlas')
        atlas.paste(im, (x, y)); place[name] = (x, y, im.width, im.height)
        x += im.width; shelf = max(shelf, im.height)
    out = ['// GENERATED by tools/gen_assets.py - where each /axeolon/block/*.png sits in terrain.rgba',
           '#include "RigAtlas.h"', '', 'const RigTexture RIG_TEXTURES[] = {']
    for name in sorted(place):
        out.append('    {"%s", %d, %d, %d, %d},' % ((name,) + place[name]))
    out += ['};', 'const int RIG_TEXTURE_COUNT = %d;' % len(place), '']
    open(os.path.join(ROOT, 'source/model/RigAtlas.cpp'), 'w').write('\n'.join(out))
    print('rig textures packed, last row ends at', y + shelf)

def gen_item_table():
    # tools/generated/items.tsv (DumpItems): id damage icon colour overlay overlayColour flags name
    rows = []
    for line in open(os.path.join(ROOT, 'tools/generated/items.tsv'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) < 8: continue
        rows.append((int(f[0]), int(f[1]), int(f[2]), int(f[3]) & 0xFFFFFF, int(f[4]), int(f[5]) & 0xFFFFFF, int(f[6]), f[7]))
    rows.sort()
    out = ['// GENERATED by tools/gen_assets.py from tools/generated/items.tsv - do not edit',
           '#include "ItemTable.h"', '', 'const ItemInfo ITEMS[] = {']
    for r in rows:
        out.append('    {%d, %d, %d, 0x%06X, %d, 0x%06X, %d, "%s"},' % (r[:7] + (r[7].replace('\\', '').replace('"', "'"),)))
    out += ['};', 'const int ITEM_COUNT = %d;' % len(rows), '']
    open(os.path.join(ROOT, 'source/game/ItemTable.cpp'), 'w', encoding='utf-8').write('\n'.join(out))

def gen_block_table(blocks):
    flags_names = []
    out = ['// GENERATED by tools/gen_assets.py from tools/generated/blocks.json - do not edit',
           '#include "BlockTable.h"', '', 'const BlockInfo BLOCKS[256] = {']
    for i in range(256):
        b = blocks.get(str(i))
        if not b:
            out.append('    {},')
            continue
        f = ['BF_EXISTS']
        if b['opaque']: f.append('BF_OPAQUE')
        if b['normal']: f.append('BF_CUBE')
        if b['liquid']: f.append('BF_LIQUID')
        cls = b['cls']
        if cls in ('BlockGlass', 'BlockIce', 'BlockBreakable', 'BlockTintedGlass', 'BlockIceBricks', 'BlockPortal'):
            f.append('BF_CULL_SAME')
        if cls in ('BlockLeaves', 'BlockLeavesBase'): f.append('BF_LEAVES')
        if cls == 'BlockStep' and b['bounds'][4] < 1.0: f.append('BF_SLAB')  # half slab: meta & 8 = top half
        mt = b['tex']
        if cls == 'BlockTintedGlass':  # each colour on its own baked tile
            mt = [[TINTED_GLASS_TILES[i]] * 6 for i in range(16)]
        tex = ','.join('{' + ','.join(str(max(t, 0)) for t in m) + '}' for m in mt)
        bounds = ','.join('%.6ff' % v for v in b['bounds'])
        name = b['disp'] or b['name']
        out.append('    {"%s", %d, %s, %d, %d, %d, {%s}, {%s}},' % (
            name.replace('"', "'"), b['render'] & 0xFF, '|'.join(f), b['pass'], b['opacity'], b['light'], bounds, tex))
    out.append('};')
    return '\n'.join(out) + '\n'

def main():
    if len(sys.argv) == 2 and sys.argv[1] == '--tables':  # just BlockTable.cpp + ItemTable.cpp
        blocks = json.load(open(os.path.join(ROOT, 'tools/generated/blocks.json')))
        open(os.path.join(ROOT, 'source/world/BlockTable.cpp'), 'w').write(gen_block_table(blocks))
        gen_item_table()
        return 0
    if len(sys.argv) < 5:
        print(__doc__)
        print('usage: gen_assets.py <textures_out> <jars/assets> <minecraft/src/axeolon> <romfs dir>')
        return 1
    tex_dir, assets_dir, axe_dir, romfs = sys.argv[1:5]
    blocks = json.load(open(os.path.join(ROOT, 'tools/generated/blocks.json')))
    open(os.path.join(ROOT, 'source/world/BlockTable.cpp'), 'w').write(gen_block_table(blocks))
    gen_item_table()

    # Block atlas: terrain.png on top, Axeolon's terrain2.png (indices 256..511) below
    a = Image.open(os.path.join(tex_dir, 'terrain.png')).convert('RGBA')
    b = Image.open(os.path.join(tex_dir, 'axeolon/terrain2.png')).convert('RGBA')
    atlas = Image.new('RGBA', (256, 1024))
    atlas.paste(a, (0, 0)); atlas.paste(b, (0, 256))
    # Rows 512+: every Blockbench block model texture (/axeolon/block/*.png), so model blocks
    # (chests, doors, furnaces...) draw in the same pass as the terrain
    pack_rig_textures(atlas, os.path.join(axe_dir, 'block'))
    # Biome tint baked in for now (Beta tints grass tops and leaves per biome at render time)
    grass = biome_colour(os.path.join(tex_dir, 'misc/grasscolor.png'), 0.8, 0.4)
    foliage = biome_colour(os.path.join(tex_dir, 'misc/foliagecolor.png'), 0.8, 0.4)
    tint(atlas, 0, grass)
    leaf_tiles = sorted({t for v in blocks.values() if v['cls'] in ('BlockLeaves', 'BlockLeavesBase')
                         for m in v['tex'] for t in m if t >= 0})
    for t in leaf_tiles: tint(atlas, t, foliage)
    # BlockTintedGlass: the glass texture times AxeolonColorLight.DYE[meta], baked into free tiles
    # (the mesher has no per-vertex colour); the block table points each colour at its tile
    glass = atlas.crop((49 % 16 * 16, 49 // 16 * 16, 49 % 16 * 16 + 16, 49 // 16 * 16 + 16))
    for meta, t in enumerate(TINTED_GLASS_TILES):
        atlas.paste(glass, (t % 16 * 16, t // 16 * 16))
        c = DYE[meta]
        tint(atlas, t, ((c >> 16) & 255, (c >> 8) & 255, c & 255))
    write_rgba(atlas, os.path.join(romfs, 'textures/terrain.rgba'))
    # Mob textures, one texture each (vanilla /mob/*.png after Axeolon's pipeline, then Axeolon's own)
    for d, out in ((os.path.join(tex_dir, 'mob'), 'textures/mob'), (os.path.join(axe_dir, 'mob'), 'axeolon/mob')):
        for fn in sorted(os.listdir(d)):
            if fn.endswith('.png'):
                write_rgba(Image.open(os.path.join(d, fn)), os.path.join(romfs, out, fn[:-4] + '.rgba'))
    # Title screen and menus: Beta's GUI sheet, dirt background, bitmap font, black.png (logo shadow),
    # Axeolon's panorama (scaled to 256x256 for the 3DS) and splash texts
    for rel in ('gui/gui.png', 'gui/background.png', 'font/default.png', 'title/black.png'):
        write_rgba(Image.open(os.path.join(tex_dir, rel)), os.path.join(romfs, 'textures', rel[:-4] + '.rgba'))
    for i in range(6):
        im = Image.open(os.path.join(axe_dir, 'title', 'panorama_%d.png' % i)).convert('RGBA').resize((256, 256), Image.LANCZOS)
        write_rgba(im, os.path.join(romfs, 'axeolon/title/panorama_%d.rgba' % i))
    import shutil
    shutil.copy(os.path.join(axe_dir, 'title', 'splashes.txt'), os.path.join(romfs, 'axeolon/title/splashes.txt'))
    # Blockbench models -> .axm
    import subprocess
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'tools/bbmodel_convert.py'), axe_dir, romfs])
    for name in ['gui/gui.png', 'gui/icons.png', 'gui/items.png', 'font/default.png', 'gui/inventory.png',
                 'terrain/sun.png', 'terrain/moon.png', 'environment/clouds.png', 'particles.png',
                 'misc/water.png', 'misc/vignette.png', 'misc/dial.png', 'item/sign.png', 'art/kz.png']:
        p = os.path.join(tex_dir, name)
        if os.path.exists(p): write_rgba(Image.open(p), os.path.join(romfs, 'textures', name[:-4] + '.rgba'))
    write_rgba(Image.open(os.path.join(axe_dir, 'gui', 'icons.png')), os.path.join(romfs, 'axeolon/gui/icons.rgba')) # mana orbs
    write_rgba(Image.open(os.path.join(axe_dir, 'gui', 'bossbar.png')), os.path.join(romfs, 'axeolon/gui/bossbar.rgba'))
    for fn in sorted(os.listdir(os.path.join(axe_dir, 'sign'))): # each wood's sign
        write_rgba(Image.open(os.path.join(axe_dir, 'sign', fn)), os.path.join(romfs, 'axeolon/sign', fn[:-4] + '.rgba'))

    # Sounds: vanilla objects back to their real names, then Axeolon's on top
    idx = json.load(open(os.path.join(assets_dir, 'indexes/b1.2.json')))['objects']
    n = 0
    for name, o in idx.items():
        if not name.endswith('.ogg'): continue
        src = os.path.join(assets_dir, 'objects', o['hash'][:2], o['hash'])
        dst = os.path.join(romfs, 'sound', name)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst); n += 1
    for dp, _, files in os.walk(os.path.join(axe_dir, 'sound')):
        for fn in files:
            if fn.endswith('.ogg'):
                rel = os.path.relpath(os.path.join(dp, fn), axe_dir)
                dst = os.path.join(romfs, 'axeolon', rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(os.path.join(dp, fn), dst); n += 1
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'tools/gen_sounds.py'), romfs])
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'tools/gen_vehicles.py'), tex_dir, romfs]) # boats in every wood, the minecart
    print('block table: %d blocks, atlas 256x1024, leaf tiles tinted: %s, sounds: %d' % (len(blocks), leaf_tiles, n))

if __name__ == '__main__':
    sys.exit(main() or 0)
