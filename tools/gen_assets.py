#!/usr/bin/env python3
"""Builds the 3DS-side data.

  gen_assets.py --tables
      source/world/BlockTable.cpp and source/game/ItemTable.cpp from tools/generated/blocks.json
      and items.tsv (tools/nsss/DumpNsss, run against the NSSS a1.1.12 jar).

  gen_assets.py <a1.1.12.jar> <pe 0.5.0 apk> <romfs dir>
      romfs/textures from the jar (terrain, gui, items, particles, font, clouds, the gear and
      leaves FX sources, boat/cart/sign) and from the MCPE 0.5.0 apk (the PE menus and touch UI:
      romfs/textures/pe). The textures NSSS takes from the unmodded Alpha 1.1.2_01 jar or its
      resources (mobs, sun and moon, paintings) and the sounds are not in either file and are
      kept as they are; gen_sounds.py turns new effect .ogg files into .snd.
"""
import json, os, struct, sys, zipfile, io
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def write_rgba(img, path):
    img = img.convert('RGBA')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(b'RGBA' + struct.pack('<HH', img.width, img.height))
        f.write(img.tobytes())

# romfs/textures/<out> <- jar entry
FROM_JAR = {
    'terrain': 'terrain.png', 'particles': 'particles.png',
    'gui/background': 'gui/background.png', 'gui/gui': 'gui/gui.png', 'gui/icons': 'gui/icons.png',
    'gui/inventory': 'gui/inventory.png', 'gui/items': 'gui/items.png',
    'environment/clouds': 'clouds.png', 'font/default': 'default.png', 'title/black': 'title/black.png',
    'mob/char': 'char.png',
    'misc/gear': 'misc/gear.png', 'misc/gearmiddle': 'misc/gearmiddle.png', 'misc/vignette': 'misc/vignette.png',
    'misc/leaves': 'leaves.png', 'misc/buds': 'buds.png', 'misc/water': 'water.png',
    'item/boat': 'item/boat.png', 'item/cart': 'item/cart.png', 'item/sign': 'item/sign.png',
}
# romfs/textures/pe/<out> <- apk entry
FROM_APK = {n: 'assets/gui/%s.png' % n for n in ('bg32', 'gui', 'gui2', 'icons', 'items', 'spritesheet', 'title', 'touchgui')}

def gen_item_table():
    # tools/generated/items.tsv (DumpItems): id damage icon colour overlay overlayColour flags name
    rows = []
    for line in open(os.path.join(ROOT, 'tools/generated/items.tsv'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) < 8: continue
        rows.append((int(f[0]), int(f[1]), int(f[2]), int(f[3]) & 0xFFFFFF, int(f[4]), int(f[5]) & 0xFFFFFF, int(f[6]), f[7]))
    rows.sort()
    out = ['// GENERATED by tools/gen_assets.py from tools/generated/items.tsv - do not edit',
           '#include "ItemTable.h"', '', 'const ItemInfo ITEMS[] = {']
    for r in rows:
        out.append('    {%d, %d, %d, 0x%06X, %d, 0x%06X, %d, "%s"},' % (r[:7] + (r[7].replace('\\', '').replace('"', "'"),)))
    out += ['};', 'const int ITEM_COUNT = %d;' % len(rows), '']
    open(os.path.join(ROOT, 'source/game/ItemTable.cpp'), 'w', encoding='utf-8').write('\n'.join(out))

def gen_block_table(blocks):
    flags_names = []
    out = ['// GENERATED by tools/gen_assets.py from tools/generated/blocks.json - do not edit',
           '#include "BlockTable.h"', '', 'const BlockInfo BLOCKS[256] = {']
    for i in range(256):
        b = blocks.get(str(i))
        if not b:
            out.append('    {},')
            continue
        f = ['BF_EXISTS']
        if b['opaque']: f.append('BF_OPAQUE')
        if b['normal']: f.append('BF_CUBE')
        if b['liquid']: f.append('BF_LIQUID')
        cls = b['cls']
        if cls in ('BlockGlass', 'BlockIce', 'BlockBreakable'):
            f.append('BF_CULL_SAME')
        if cls in ('BlockLeaves', 'BlockLeavesBase'): f.append('BF_LEAVES')
        if cls == 'BlockStep' and b['bounds'][4] < 1.0: f.append('BF_SLAB')  # half slab: meta & 8 = top half
        mt = b['tex']
        # getBlockTextureFromSideAndMetadata; negative = drawn mirrored (BlockDoor), -1 = threw
        tex = ','.join('{' + ','.join(str(0 if t == -1 else t) for t in m) + '}' for m in mt)
        bounds = ','.join('%.6ff' % v for v in b['bounds'])
        name = b['disp'] or b['name']
        out.append('    {"%s", %d, %s, %d, %d, %d, %d, {%s}, {%s}},' % (
            name.replace('"', "'"), b['render'] & 0xFF, '|'.join(f), b['pass'], b['opacity'], b['light'], b.get('index', 0), bounds, tex))
    out.append('};')
    return '\n'.join(out) + '\n'

def main():
    if len(sys.argv) == 2 and sys.argv[1] == '--tables':
        blocks = json.load(open(os.path.join(ROOT, 'tools/generated/blocks.json')))
        open(os.path.join(ROOT, 'source/world/BlockTable.cpp'), 'w').write(gen_block_table(blocks))
        gen_item_table()
        return 0
    if len(sys.argv) != 4:
        print(__doc__)
        return 1
    jar, apk, romfs = zipfile.ZipFile(sys.argv[1]), zipfile.ZipFile(sys.argv[2]), sys.argv[3]
    for out, src, z in [(o, s, jar) for o, s in FROM_JAR.items()] + [('pe/' + o, s, apk) for o, s in FROM_APK.items()]:
        write_rgba(Image.open(io.BytesIO(z.read(src))), os.path.join(romfs, 'textures', out + '.rgba'))
    print('textures: %d from the jar, %d from the apk' % (len(FROM_JAR), len(FROM_APK)))

if __name__ == '__main__':
    sys.exit(main() or 0)
