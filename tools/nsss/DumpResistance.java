import com.mojang.minecraft.core.level.tile.Block;
// source/world/BlockResistance.h from the NSSS jar: Block.getExplosionResistance(null) for every id
// usage: java -cp out:a1.1.12.jar DumpResistance > source/world/BlockResistance.h
public class DumpResistance {
  public static void main(String[] a) throws Exception {
    Class.forName("com.mojang.minecraft.core.level.tile.Block");
    StringBuilder s = new StringBuilder("#pragma once\n// GENERATED by tools/nsss/DumpResistance.java: Block.getExplosionResistance (blockResistance / 5).\nconstexpr float BLOCK_RESISTANCE[256] = {\n");
    for (int i = 0; i < 256; i++) {
      Block b = Block.allBlocks[i];
      s.append(b == null ? 0.0F : b.getExplosionResistance(null)).append('f').append(i == 255 ? "\n" : (i % 8 == 7 ? ",\n" : ","));
    }
    s.append("};\n");
    System.out.print(s);
  }
}
