#!/usr/bin/env python3
"""tools/generated/physics.txt (DumpPhysics) -> source/world/PhysicsTable.cpp"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
info = {}
boxes = {}
for line in open(os.path.join(ROOT, 'tools/generated/physics.txt')):
    f = line.split()
    if not f: continue
    if f[0] == 'B':
        info[int(f[1])] = (int(f[2]), int(f[3]), int(f[4]), int(f[5]), int(f[6]), int(f[7]), float(f[8]), int(f[9]))
    elif f[0] == 'C':
        n = int(f[3])
        boxes[(int(f[1]), int(f[2]))] = [tuple(float(v) for v in f[4 + 6 * i:10 + 6 * i]) for i in range(n)]
# de-duplicate box lists
pool = []
index = {}
def ref(lst):
    key = tuple(lst)
    if key not in index:
        index[key] = (len(pool), len(lst))
        pool.extend(lst)
    return index[key]
out = ['// GENERATED by tools/gen_physics.py from tools/generated/physics.txt (tools/nsss DumpNsssPhysics)',
       '#include "PhysicsTable.h"', '']
refs = {}
for id in range(256):
    for meta in range(16):
        refs[(id, meta)] = ref(boxes.get((id, meta), []))
out.append('const float COLLISION_BOXES[][6] = {')
for b in pool or [(0,) * 6]:
    out.append('    {%s},' % ', '.join('%rf' % v for v in b))
out.append('};')
out.append('const BlockPhysics BLOCK_PHYSICS[256] = {')
for id in range(256):
    i = info.get(id, (0, 0, 0, 0, 0, 0, 0.6, 0))
    rs = ', '.join('{%d, %d}' % refs[(id, m)] for m in range(16))
    out.append('    {%d, %d, %d, %d, %d, %d, %rf, %d, {%s}},' % (i[0], i[1], i[2], i[3], i[4], i[5], i[6], i[7], rs))
out.append('};')
open(os.path.join(ROOT, 'source/world/PhysicsTable.cpp'), 'w').write('\n'.join(out) + '\n')
print('physics table:', len(pool), 'boxes')
