# tools/generated/{survival,drops}.txt (tools/nsss/DumpNsss) -> source/game/SurvivalData.cpp
import os
here = os.path.dirname(os.path.abspath(__file__))
hard = {}; items = {}; tools = {}; shaped = []; shapeless = []; smelt = []; order = []
for l in open(os.path.join(here, 'generated/survival.txt')):
    p = l.split()
    if not p: continue
    if p[0] == 'B': hard[int(p[1])] = float(p[2])
    # max damage <= 0 means "never wears out" in Java (NSSS's quiver and sponge armour are -16383)
    elif p[0] == 'I': items[int(p[1])] = (int(p[2]), max(0, int(p[3])), int(p[4]))
    elif p[0] == 'T':
        lst = []
        for e in p[2:]:
            k, v = e.split('=')
            h = v.endswith('h')
            lst.append((int(k), float(v.rstrip('h')), h))
        tools[int(p[1])] = lst
    elif p[0] == 'S':
        w, h = int(p[1]), int(p[2]); out = p[3].split(':'); ins = p[4:]
        order.append(len(shaped)); shaped.append((w, h, out, ins))
    elif p[0] == 'L':
        order.append(~len(shapeless)); shapeless.append((p[1].split(':'), p[2:]))
    elif p[0] == 'F':
        smelt.append((int(p[1]), p[2].split(':')))
drops = {}
for l in open(os.path.join(here, 'generated/drops.txt')):
    p = l.split()
    drops[(int(p[1]), int(p[2]))] = (p[3], int(p[4]), p[5])
def ing(s):
    if s == '-': return '{-1, 0}'
    i, d = s.split(':'); return '{%s, %s}' % (i, d)
o = ['// Generated by tools/gen_survival.py from the NSSS jar (tools/nsss/DumpNsss). Do not edit.',
     '#include "Survival.h"', '', 'namespace survival {', '']
o.append('const float HARDNESS[256] = {' + ', '.join(('%sf' % repr(hard[i])) if i in hard else '0.0f' for i in range(256)) + '};')
o.append('')
o.append('// {dropId (-2 = random, ported in Blocks.cpp), damage, quantity (-2 = random)}')
o.append('const Drop DROPS[256][16] = {')
for i in range(256):
    row = []
    for m in range(16):
        d = drops.get((i, m))
        if not d: row.append('{0, 0, 0}'); continue
        did = -2 if d[0] == 'R' else int(d[0]); q = -2 if d[2] == 'R' else int(d[2])
        row.append('{%d, %d, %d}' % (did, d[1], q))
    o.append('    {' + ', '.join(row) + '},')
o.append('};')
o.append('')
o.append('const ItemData ITEM_DATA[] = {')
for i in sorted(items): o.append('    {%d, %d, %d, %d},' % (i, *items[i]))
o.append('};')
o.append('const int ITEM_DATA_COUNT = %d;' % len(items))
o.append('')
o.append('const ToolEntry TOOL_ENTRIES[] = {')
for i in sorted(tools):
    for k, v, h in tools[i]: o.append('    {%d, %d, %sf, %s},' % (i, k, repr(v), 'true' if h else 'false'))
o.append('};')
o.append('const int TOOL_ENTRY_COUNT = %d;' % sum(len(v) for v in tools.values()))
o.append('')
o.append('const Shaped SHAPED[] = {')
for w, h, out, ins in shaped:
    ins = ins + ['-'] * (9 - len(ins))
    o.append('    {%d, %d, {%s, %s, %s}, {%s}},' % (w, h, out[0], out[2], out[1], ', '.join(ing(x) for x in ins)))
o.append('};')
o.append('const int SHAPED_COUNT = %d;' % len(shaped))
o.append('const Shapeless SHAPELESS[] = {')
for out, ins in shapeless:
    o.append('    {{%s, %s, %s}, %d, {%s}},' % (out[0], out[2], out[1], len(ins), ', '.join(ing(x) for x in ins + ['-'] * (9 - len(ins)))))
o.append('};')
o.append('const int SHAPELESS_COUNT = %d;' % len(shapeless))
o.append('const Smelt SMELTING[] = {')
for i, out in smelt: o.append('    {%d, {%s, %s, %s}},' % (i, out[0], out[2], out[1]))
o.append('};')
o.append('const int SMELT_COUNT = %d;' % len(smelt))
o.append('// CraftingManager.recipes in the jar order: n >= 0 is SHAPED[n], n < 0 is SHAPELESS[~n]')
o.append('const int16_t RECIPE_ORDER[] = {' + ', '.join(str(x) for x in order) + '};')
o.append('const int RECIPE_COUNT = %d;' % len(order))
o.append('} // namespace survival')
open(os.path.join(here, '../source/game/SurvivalData.cpp'), 'w').write('\n'.join(o) + '\n')
