# tools/generated/blockprops.tsv (tools/java/DumpBlockProps.java) -> source/world/BlockProps.{h,cpp}
import os, re
here = os.path.dirname(os.path.abspath(__file__))
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(here, 'generated/blockprops.tsv'))]
MATS = ['air','ground','wood','rock','iron','water','lava','leaves','plants','sponge','cloth','fire','sand','circuits',
        'glass','tnt','unused','ice','snow','builtSnow','cactus','clay','pumpkin','portal','field_21150_y',
        'wug', 'web'] # the last two are NSSS's
# BC: every class the table uses, plus every BC:: the engine code still names (Beta/Axeolon blocks
# NSSS doesn't have), so the code keeps compiling while it's converted
import glob
used = set()
for fn in glob.glob(os.path.join(here, '../source/**/*.cpp'), recursive=True) + glob.glob(os.path.join(here, '../source/**/*.h'), recursive=True):
    if fn.endswith('BlockProps.h'): continue
    used |= set(re.findall(r'BC::(\w+)', open(fn, encoding='utf-8', errors='ignore').read()))
classes = sorted(set(r[2] for r in rows) | {('Block' + u) for u in used if u not in ('None', 'Plain')})
h = ['#pragma once', '// Generated by tools/gen_blockprops.py from the mod\'s own Block classes. Do not edit.',
     '#include <cstdint>', '',
     'enum class Mat : uint8_t { ' + ', '.join(('cake' if m == 'field_21150_y' else m) for m in MATS) + ' };',
     '// Material.isSolid / getIsSolid / getIsLiquid / getCanBlockGrass (same answers for the first two in Beta)',
     'inline bool matSolid(Mat m) { return !(m == Mat::air || m == Mat::fire || m == Mat::water || m == Mat::lava || m == Mat::plants || m == Mat::circuits || m == Mat::snow); }',
     'inline bool matLiquid(Mat m) { return m == Mat::water || m == Mat::lava; }',
     'inline bool matBlocksGrass(Mat m) { return !(m == Mat::air || m == Mat::fire || m == Mat::plants || m == Mat::circuits || m == Mat::snow); }',
     '', 'enum class BC : uint8_t { None, ' + ', '.join(c[5:] if c.startswith('Block') and len(c) > 5 else 'Plain' for c in classes) + ' };',
     '', 'struct BlockProps {', '    BC cls;', '    Mat mat;', '    uint8_t opacity, light;', '    uint16_t tickRate;',
     '    bool opaqueCube, normal, container, tickOnLoad;', '    bool opaqueLookup; // Block.opaqueCubeLookup (Axeolon clears it for leaves; Beta never set it for 43)', '};', '', 'extern const BlockProps BP[256];',
     'inline Mat blockMat(uint8_t id) { return BP[id].mat; }', '',
     '// Block.stepSound: StepSound.func_1145_d (steps), func_1146_a (breaking), volume, pitch',
     'struct BlockSound { const char* step; const char* brk; float volume, pitch; };',
     'extern const BlockSound BS[256];', '']
c = ['#include "BlockProps.h"', '', 'const BlockProps BP[256] = {']
byid = {int(r[0]): r for r in rows}
for i in range(256):
    r = byid.get(i)
    if not r:
        c.append('    {BC::None, Mat::air, 0, 0, 0, false, false, false, false, false},')
        continue
    cls = r[2]
    cn = cls[5:] if cls.startswith('Block') and len(cls) > 5 else 'Plain'
    m = 'cake' if r[3] == 'field_21150_y' else r[3]
    b = lambda v: 'true' if v == '1' else 'false'
    c.append(f'    {{BC::{cn}, Mat::{m}, {r[4]}, {r[5]}, {r[8]}, {b(r[6])}, {b(r[7])}, {b(r[9])}, {b(r[10])}, {b(r[11])}}}, // {i} {r[1]}')
c.append('};')
c += ['', 'const BlockSound BS[256] = {']
for i in range(256):
    r = byid.get(i)
    if not r or len(r) < 16:
        c.append('    {"step.stone", "step.stone", 1.0f, 1.0f},')
    else:
        c.append(f'    {{"{r[12]}", "{r[13]}", {float(r[14])!r}f, {float(r[15])!r}f}}, // {i}')
c.append('};')
src = os.path.join(here, '../source/world')
open(os.path.join(src, 'BlockProps.h'), 'w').write('\n'.join(h))
open(os.path.join(src, 'BlockProps.cpp'), 'w').write('\n'.join(c) + '\n')
